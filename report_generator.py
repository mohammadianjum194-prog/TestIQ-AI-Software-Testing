"""
report_generator.py – CSV and text report generation for TestIQ.

Generates downloadable reports from the data stored in SQLite:
    - Test case CSV
    - Test results CSV
    - Defect CSV
    - Complete testing summary (text + optional CSV)

All reports are written to the /reports directory and returned as
file paths so the Streamlit UI can serve them as downloads.
"""

import csv
import io
import logging
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from config import APP_NAME, APP_VERSION, REPORTS_DIR

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# CSV helpers
# ---------------------------------------------------------------------------

def _write_csv(rows: List[Dict[str, Any]], fieldnames: List[str]) -> bytes:
    """Serialise rows to CSV bytes (UTF-8 with BOM for Excel compatibility)."""
    buf = io.StringIO()
    writer = csv.DictWriter(
        buf, fieldnames=fieldnames, extrasaction="ignore", lineterminator="\r\n"
    )
    writer.writeheader()
    writer.writerows(rows)
    return buf.getvalue().encode("utf-8-sig")


# ---------------------------------------------------------------------------
# Individual report generators
# ---------------------------------------------------------------------------

def generate_test_cases_csv(test_cases: List[Dict[str, Any]]) -> bytes:
    """Return CSV bytes for the provided test-case list."""
    fields = [
        "test_id", "requirement_id", "scenario", "preconditions",
        "test_data", "expected_result", "test_type", "priority",
        "status", "created_at",
    ]
    return _write_csv(test_cases, fields)


def generate_test_results_csv(results: List[Dict[str, Any]]) -> bytes:
    """Return CSV bytes for the provided test-result list."""
    fields = [
        "test_id", "input_data", "expected_result", "actual_result",
        "status", "execution_time", "executed_at",
    ]
    return _write_csv(results, fields)


def generate_defects_csv(defects: List[Dict[str, Any]]) -> bytes:
    """Return CSV bytes for the provided defect list."""
    fields = [
        "defect_id", "test_id", "title", "description",
        "expected_result", "actual_result", "severity",
        "priority", "status", "created_at",
    ]
    return _write_csv(defects, fields)


def generate_summary_text(metrics: Dict[str, Any]) -> bytes:
    """
    Generate a plain-text testing summary report.

    Parameters
    ----------
    metrics : dict returned by database.get_dashboard_metrics()
    """
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [
        "=" * 60,
        f"  {APP_NAME} – Testing Summary Report",
        f"  Version: {APP_VERSION}",
        "=" * 60,
        "",
        f"  Project          : {APP_NAME}",
        f"  Report Generated : {now}",
        "",
        "  REQUIREMENT COVERAGE",
        "  " + "-" * 40,
        f"  Total Requirements : {metrics.get('total_requirements', 0)}",
        f"  Total Test Cases   : {metrics.get('total_test_cases', 0)}",
        "",
        "  TEST EXECUTION SUMMARY",
        "  " + "-" * 40,
        f"  Total Executed     : {metrics.get('total_executed', 0)}",
        f"  Passed             : {metrics.get('passed', 0)}",
        f"  Failed             : {metrics.get('failed', 0)}",
        f"  Blocked            : {metrics.get('blocked', 0)}",
        f"  Pass Rate          : {metrics.get('pass_rate', 0.0):.1f}%",
        "",
        "  DEFECT SUMMARY",
        "  " + "-" * 40,
        f"  Total Defects      : {metrics.get('total_defects', 0)}",
        f"  Critical           : {metrics.get('critical_defects', 0)}",
        f"  Major              : {metrics.get('major_defects', 0)}",
        f"  Minor              : {metrics.get('minor_defects', 0)}",
        f"  Trivial            : {metrics.get('trivial_defects', 0)}",
        "",
        "  QUALITY ASSESSMENT",
        "  " + "-" * 40,
    ]

    pass_rate = metrics.get("pass_rate", 0.0)
    if pass_rate >= 90:
        quality = "EXCELLENT – Ready for release consideration."
    elif pass_rate >= 75:
        quality = "GOOD – Minor issues to address before release."
    elif pass_rate >= 50:
        quality = "FAIR – Significant defects require resolution."
    else:
        quality = "POOR – Major quality issues; not suitable for release."

    lines += [
        f"  Overall Quality    : {quality}",
        "",
        "=" * 60,
        f"  Generated by {APP_NAME} v{APP_VERSION}",
        "=" * 60,
    ]

    return "\n".join(lines).encode("utf-8")


def generate_full_report_csv(
    requirements: List[Dict],
    test_cases: List[Dict],
    test_results: List[Dict],
    defects: List[Dict],
    metrics: Dict[str, Any],
) -> bytes:
    """
    Generate a single CSV containing a summary section followed by
    defect and result details – useful as an all-in-one download.
    """
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\r\n")

    # Summary header
    w.writerow(["TestIQ – Complete Testing Report"])
    w.writerow(["Generated", datetime.now().strftime("%Y-%m-%d %H:%M:%S")])
    w.writerow([])
    w.writerow(["METRICS"])
    for key, val in metrics.items():
        w.writerow([key.replace("_", " ").title(), val])

    # Test Cases
    w.writerow([])
    w.writerow(["TEST CASES"])
    if test_cases:
        w.writerow(test_cases[0].keys())
        for tc in test_cases:
            w.writerow(tc.values())

    # Test Results
    w.writerow([])
    w.writerow(["TEST RESULTS"])
    if test_results:
        w.writerow(test_results[0].keys())
        for tr in test_results:
            w.writerow(tr.values())

    # Defects
    w.writerow([])
    w.writerow(["DEFECTS"])
    if defects:
        w.writerow(defects[0].keys())
        for d in defects:
            w.writerow(d.values())

    return buf.getvalue().encode("utf-8-sig")
